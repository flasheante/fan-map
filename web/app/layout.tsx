import type { Metadata } from "next";
import { GoogleAnalytics } from "@next/third-parties/google";
import { Archivo, Geist, Geist_Mono } from "next/font/google";
import { AuthProvider } from "@/components/auth/auth-provider";
import { SiteHeader } from "@/components/site-header";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Tipografía bold/uppercase de la marca The Warning (landing "/" y toda la
// sección /artists/the-warning — ver su layout.tsx). Se declara acá, en el
// layout raíz, para que la variable CSS quede disponible en cualquier
// página sin que cada una tenga que cargar su propia instancia de Archivo.
const archivo = Archivo({
  variable: "--font-warning-display",
  weight: ["700", "900"],
  subsets: ["latin"],
});

// ID de medición de GA4 (G-XXXXXXXXXX), seteado sólo en Vercel (Production).
// Sin la variable (dev local, tests) no se carga el script ni se mandan
// datos. Las navegaciones client-side del App Router las registra GA4 solo
// vía "medición mejorada" (cambios de historial), sin código extra.
const GA_ID = process.env.NEXT_PUBLIC_GA_ID;

export const metadata: Metadata = {
  title: "Fan Map",
  description: "Generated by flasheante",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} ${archivo.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <AuthProvider>
          {/* Header fijo de todo el sitio (no se muestra en la landing "/"). */}
          <SiteHeader />
          {children}
        </AuthProvider>
      </body>
      {GA_ID && <GoogleAnalytics gaId={GA_ID} />}
    </html>
  );
}
